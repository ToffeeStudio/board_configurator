// Actual React Debug/slider components, isolated visible browser, fake HID only.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {open} from 'node:fs/promises';
import path from 'node:path';
const [dependencies, baseUrl, reportPath, screenshotPath] = process.argv.slice(2);
if (!dependencies || !baseUrl || !reportPath || !screenshotPath)
  throw new Error('Required: NODE_MODULES_DIRECTORY LOCAL_APP_URL NEW_REPORT_JSON SCREENSHOT_PNG.');
assert.equal(new URL(baseUrl).hostname, '127.0.0.1');
const report = await open(reportPath, 'wx');
const {chromium} = createRequire(path.join(dependencies, 'package.json'))('playwright-core');
const browser = await chromium.launch({headless: false, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page = await browser.newPage({viewport: {width: 1280, height: 850}});
page.setDefaultTimeout(12000);
const checks: string[] = [], errors: string[] = [];
page.on('pageerror', (error: Error) => {errors.push(error.message); console.error('UI ERROR:', error.message);});
const check = (label: string) => {checks.push(label); console.log('OFFLINE UI PASS:', label);};
const counts = () => page.evaluate(() => {
  const f = (window as any).powerFixture;
  return {reads: f.reads, writes: f.writes, maximumPending: f.maximumPending, level: f.level};
});
const set = (fields: Record<string, unknown>) => page.evaluate((values: Record<string, unknown>) => Object.assign((window as any).powerFixture, values), fields);
try {
  // The app's HTML plugin redirects navigation requests to its SPA entry.
  // Fetch the Vite-transformed fixture without the navigation Accept header.
  const fixtureUrl = new URL('/tests/power-debug-fixture.html', baseUrl).href;
  const html = await (await fetch(fixtureUrl, {headers: {accept: '*/*'}})).text();
  await page.route(fixtureUrl, (route: any) => route.fulfill({contentType: 'text/html', body: html}));
  await page.goto(fixtureUrl);
  await page.getByRole('button', {name: 'Debug: current budget'}).waitFor();
  await page.waitForTimeout(400);
  assert.deepEqual(await counts(), {reads: 0, writes: 0, maximumPending: 0, level: 0});
  check('Debug off does not open a telemetry loop or write lighting');
  await page.getByRole('button', {name: 'Debug: current budget'}).click();
  await page.getByTestId('power-requested').filter({hasText: '0 mA'}).waitFor();
  assert.equal((await counts()).writes, 0);
  check('Debug reads telemetry without any lighting setter');
  await page.getByTestId('power-output-caps').filter({hasText: 'front 0–200/255 · rear 0–255/255 · badge 0–200/255'}).waitFor();
  await set({frontBadgeMax: 150});
  await page.getByTestId('power-output-caps').filter({hasText: 'front 0–150/255'}).waitFor();
  assert.equal((await counts()).writes, 0);
  await set({schema: 1});
  await page.getByTestId('power-output-caps').waitFor({state: 'detached'});
  await set({schema: 2, frontBadgeMax: 200});
  await page.getByTestId('power-output-caps').filter({hasText: 'front 0–200/255'}).waitFor();
  check('Debug reads output maxima from firmware, never guesses on v1 and never writes a cap');
  const slider = page.getByRole('slider', {name: 'Fixture brightness'});
  await slider.focus(); await slider.press('End');
  await page.getByTestId('power-requested').filter({hasText: '765 mA'}).waitFor();
  assert.equal(await page.getByTestId('power-effective').innerText(), '225 mA');
  assert.equal(await page.getByTestId('power-usage').innerText(), '100%');
  await page.getByText('Limiting active', {exact: false}).waitFor();
  assert.equal((await counts()).level, 255);
  check('Keyboard slider change updates current/usage without rewriting requested brightness');
  await page.screenshot({path: screenshotPath, fullPage: true});
  const beforeManual = await counts();
  await set({manual: true});
  await page.getByText('LIMITER DISABLED', {exact: false}).waitFor();
  await page.getByText('Above informational allowance', {exact: false}).waitFor();
  assert.equal(await page.getByTestId('power-effective').innerText(), '765 mA');
  assert.equal(await page.getByTestId('power-usage').innerText(), '340%');
  assert.equal(await page.getByText('Within configured budget.', {exact: true}).count(), 0);
  assert.equal((await counts()).writes, beforeManual.writes);
  assert.equal(await page.getByTestId('power-output-caps').count(), 0);
  await page.screenshot({path: screenshotPath + '.manual.png', fullPage: true});
  check('Manual firmware shows limiter disabled and over-reference output, without timeout claims or writes');
  await set({manual: false, currentUnlimited: true});
  await page.getByText('CURRENT LIMITER DISABLED', {exact: false}).waitFor();
  await page.getByTestId('power-output-caps').filter({hasText: 'front 0–200/255'}).waitFor();
  assert.equal(await page.getByTestId('power-effective').innerText(), '765 mA');
  assert.equal((await counts()).writes, beforeManual.writes);
  check('Normal current-unlimited is explicitly distinct from manual, retains cap reporting and does not claim enforcement');
  await set({currentUnlimited: false});
  await page.getByText('Limiting active', {exact: false}).waitFor();
  const box = await slider.boundingBox(); assert.ok(box);
  await page.mouse.click(box.x + box.width * 0.1, box.y + box.height / 2);
  await page.waitForFunction(() => {
    const f = (window as any).powerFixture;
    return f.level > 0 && f.level < 75 && document.querySelector('[data-testid="power-requested"]')?.textContent === `${f.level * 3} mA`;
  });
  await page.getByText('Within configured budget.', {exact: true}).waitFor();
  check('Mouse slider change refreshes the actual Debug component');
  await set({delay: 400});
  for (let n = 0; n < 15; n++) await slider.press('ArrowRight');
  await page.waitForTimeout(1000);
  assert.equal((await counts()).maximumPending, 1);
  await set({delay: 0});
  check('Slow replies and rapid slider changes never overlap HID exchanges');
  // Drain the slider queue before isolating visibility/poll behaviour.
  await page.waitForFunction(() => (window as any).powerFixture.pending === 0);
  await page.getByRole('button', {name: 'Hide Debug'}).click();
  await page.waitForTimeout(600);
  const stopped = await counts(); await page.waitForTimeout(600);
  assert.equal((await counts()).reads, stopped.reads);
  check('Closing Debug stops polling');
  await page.getByRole('button', {name: 'Debug: current budget'}).click();
  await page.getByTestId('power-requested').waitFor();
  await page.evaluate(() => {Object.defineProperty(document, 'hidden', {value: true, configurable: true}); document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForTimeout(350); const hidden = await counts(); await page.waitForTimeout(500);
  assert.equal((await counts()).reads, hidden.reads);
  await page.evaluate(() => {Object.defineProperty(document, 'hidden', {value: false, configurable: true}); document.dispatchEvent(new Event('visibilitychange'));});
  await page.getByTestId('power-requested').waitFor();
  check('Hidden pages pause telemetry; becoming visible resumes it');
  await set({delay: 400});
  for (let n = 0; n < 15; n++) await slider.press('ArrowRight');
  await page.getByText('No fresh output estimate.', {exact: false}).waitFor();
  assert.equal(await page.getByTestId('power-requested').count(), 0);
  await set({delay: 0});
  await page.getByTestId('power-requested').waitFor();
  check('Host-side age expires the last reading while telemetry waits behind queued sliders');
  await set({stale: true}); await page.getByText('No fresh output estimate.', {exact: false}).waitFor();
  assert.equal(await page.getByTestId('power-requested').count(), 0);
  await set({stale: false, unconfigured: true});
  await page.getByText('Budget not configured', {exact: false}).waitFor();
  assert.equal(await page.getByTestId('power-usage').innerText(), 'Unavailable');
  assert.equal(await page.getByTestId('power-effective').innerText(), '0 mA');
  check('Stale and unconfigured data never appear as a fresh validated budget');
  await set({reject: true}); await page.getByRole('alert').waitFor();
  const failed = await counts(); await page.waitForTimeout(600);
  assert.equal((await counts()).reads, failed.reads);
  await set({reject: false, unconfigured: false});
  await page.getByRole('button', {name: 'Retry debug'}).click();
  await page.getByTestId('power-requested').waitFor();
  check('Unsupported firmware stops the loop; explicit retry recovers');
  await page.evaluate(() => (window as any).disconnectFixture());
  await page.getByText('Board disconnected.', {exact: false}).waitFor();
  await page.waitForTimeout(400); const disconnected = await counts(); await page.waitForTimeout(400);
  assert.equal((await counts()).reads, disconnected.reads);
  await page.getByRole('button', {name: 'Toggle selected device'}).click();
  await page.getByText('Connect and select your board.', {exact: true}).waitFor();
  await page.getByRole('button', {name: 'Toggle selected device'}).click();
  await page.getByTestId('power-requested').waitFor();
  check('Disconnect clears readings and selected-device replacement reconnects cleanly');
  await page.route('**/src/config/debug.ts*', async (route: any) => {
    const response = await route.fetch(), source = await response.text();
    assert.ok(source.includes('DEBUG_ENABLED = true'));
    await route.fulfill({response, body: source.replace('DEBUG_ENABLED = true', 'DEBUG_ENABLED = false')});
  });
  await page.reload();
  await page.getByRole('heading', {name: 'Offline Debug UI test'}).waitFor();
  assert.equal(await page.getByRole('button', {name: 'Debug: current budget'}).count(), 0);
  assert.equal(await page.getByTestId('power-output-caps').count(), 0);
  await page.waitForTimeout(500);
  assert.equal((await counts()).reads, 0);
  check('Source DEBUG_ENABLED=false hides the entire panel/caps and prevents polling');
  assert.deepEqual(errors, []);
  await report.writeFile(JSON.stringify({scope: 'OFFLINE components and simulated HID only; no PCB access', checks, errors, counts: await counts()}, null, 2));
} catch (failure) {
  await report.writeFile(JSON.stringify({scope: 'OFFLINE; no PCB access', checks, errors, failure: String(failure), body: await page.locator('body').innerText()}, null, 2));
  throw failure;
} finally {
  await browser.close();
  await report.close();
}
